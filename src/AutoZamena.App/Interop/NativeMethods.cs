    public static (IntPtr FocusHwnd, IntPtr TopHwnd, IntPtr ActiveHkl, uint ProcessId) GetActiveFocusAndLayout()
    {
        IntPtr topHwnd = GetForegroundWindow();
        if (topHwnd == IntPtr.Zero)
        {
            return (IntPtr.Zero, IntPtr.Zero, GetKeyboardLayout(0), 0);
        }

        uint topTid = GetWindowThreadProcessId(topHwnd, out uint pid);
        var gui = new GUITHREADINFO { cbSize = Marshal.SizeOf<GUITHREADINFO>() };
        if (GetGUIThreadInfo(topTid, ref gui) && gui.hwndFocus != IntPtr.Zero)
        {
            uint focusTid = GetWindowThreadProcessId(gui.hwndFocus, out uint focusPid);
            IntPtr hkl = GetKeyboardLayout(focusTid);
            return (gui.hwndFocus, topHwnd, hkl, focusPid != 0 ? focusPid : pid);
        }

        return (topHwnd, topHwnd, GetKeyboardLayout(topTid), pid);
    }
